#!/usr/bin/env python3
"""Generate the web's methodology modules from ``packages/methodology`` (FON-120).

    uv run --project apps/worker python scripts/gen_methodology.py           # (re)write
    uv run --project apps/worker python scripts/gen_methodology.py --check   # exit 1 on drift

Writes (all under ``apps/web/src/lib/methodology/``):

    content.generated.ts                 METHODOLOGY_PAGES (page chrome per level) and
                                         METHODOLOGY_SECTIONS — every section's id,
                                         title, decisions, anchors, keywords and which
                                         bundled levels it carries.
    conceptual.generated.ts              CONCEPTUAL: section id → the parsed AST of the
                                         ``conceptual`` level (the public page's bundle).
    engineering.generated.ts             ENGINEERING: the ``engineering`` level, imported
                                         only by the diagnostics-gated route so the
                                         public page's chunk never carries it.
    managementFeeGuidance.generated.ts   from data/management_fee_guidance.yaml — the
                                         same facts the worker renders into the
                                         ``mgmt-fee-guidance`` slot.

``detailed`` is NEVER emitted: the web fetches it from ``GET /methodology?level=
detailed`` behind the worker's admin gate, so a member cannot read it out of
the JS bundle.

The output is a pure function of the package (no timestamps), so ``--check`` is
a byte-for-byte comparison and runs in CI as the drift gate — the same pattern
as ``apps/worker/scripts/gen_ontology.py``. The parser and validator are the
worker's (``apps/worker/app/methodology``), so the web, the worker's routes
and Atlas read one interpretation of the markdown; run through ``uv run
--project apps/worker`` so PyYAML and the concept registry are importable.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
WORKER_ROOT = REPO_ROOT / "apps" / "worker"
WEB_METHODOLOGY_DIR = REPO_ROOT / "apps" / "web" / "src" / "lib" / "methodology"
PACKAGE_ROOT = REPO_ROOT / "packages" / "methodology"

if str(WORKER_ROOT) not in sys.path:
    sys.path.insert(0, str(WORKER_ROOT))

HEADER = (
    "// AUTO-GENERATED by scripts/gen_methodology.py from packages/methodology/\n"
    "// — DO NOT EDIT BY HAND. Edit the section markdown, then regenerate:\n"
    "//   uv run --project apps/worker python scripts/gen_methodology.py\n"
    "// CI fails on drift: scripts/gen_methodology.py --check\n"
    "/* eslint-disable */\n\n"
)

WEB_LEVELS: tuple[str, ...] = ("conceptual", "engineering")


def _ts(value: Any) -> str:
    return json.dumps(value, indent=2, ensure_ascii=False)


def _ts_compact(value: Any) -> str:
    """The AST is large; one compact literal per file keeps the bundle small."""
    return json.dumps(value, separators=(",", ":"), ensure_ascii=False)


def render_content_ts(pkg: Any) -> str:
    sections: list[dict[str, Any]] = []
    for s in pkg.sections:
        sections.append(
            {
                "id": s.id,
                "title": s.title,
                "decisions": s.decisions,
                "anchors": s.anchors,
                "keywords": s.keywords,
                "hasDetailed": s.has("detailed"),
                "levels": [lvl for lvl in WEB_LEVELS if s.has(lvl)],
            }
        )
    out = [HEADER]
    out.append("import type { MethodologyPages, MethodologySection } from './types';\n\n")
    out.append(f"export const METHODOLOGY_VERSION = {int(pkg.version)} as const;\n\n")
    out.append(f"export const METHODOLOGY_PAGES: MethodologyPages = {_ts(pkg.pages)};\n\n")
    out.append(f"export const METHODOLOGY_SECTIONS: readonly MethodologySection[] = {_ts(sections)};\n")
    return "".join(out)


def render_level_ts(pkg: Any, level: str) -> str:
    const = level.upper()
    content = {
        s.id: {"title": s.level_title(level), "blocks": s.levels[level].blocks}
        for s in pkg.sections
        if s.has(level)
    }
    out = [HEADER]
    out.append("import type { LevelContent } from './types';\n\n")
    out.append(f"/** The `{level}` level of every section that has one, keyed by section id. */\n")
    out.append(f"export const {const}: Readonly<Record<string, LevelContent>> = {_ts_compact(content)};\n")
    return "".join(out)


def render_guidance_ts(data: dict[str, Any]) -> str:
    out = [HEADER]
    out.append("import type { OperatingModelId } from '@/lib/operatingModel';\n\n")
    out.append(
        "/** Directional management-fee guidance — packages/methodology/data/management_fee_guidance.yaml. */\n"
    )
    out.append(f"export const MGMT_FEE_GUIDANCE_DISCLAIMER = {json.dumps(data['disclaimer'], ensure_ascii=False)};\n\n")
    labels = {m["id"]: m["label"] for m in data["models"]}
    guidance = {m["id"]: m["guidance"] for m in data["models"]}
    out.append(f"export const OPERATING_MODEL_LABELS: Readonly<Record<OperatingModelId, string>> = {_ts(labels)};\n\n")
    out.append(
        f"export const MGMT_FEE_GUIDANCE_BY_MODEL: Readonly<Record<OperatingModelId, string>> = {_ts(guidance)};\n\n"
    )
    out.append(
        f"export const OPERATING_MODEL_ORDER: readonly OperatingModelId[] = {_ts([m['id'] for m in data['models']])};\n"
    )
    return "".join(out)


def outputs() -> dict[Path, str]:
    from app.methodology.loader import load_package
    from app.methodology.slots import management_fee_guidance

    pkg = load_package(PACKAGE_ROOT, repo_root=REPO_ROOT)
    guidance = management_fee_guidance(str(PACKAGE_ROOT / "data" / "management_fee_guidance.yaml"))
    return {
        WEB_METHODOLOGY_DIR / "content.generated.ts": render_content_ts(pkg),
        WEB_METHODOLOGY_DIR / "conceptual.generated.ts": render_level_ts(pkg, "conceptual"),
        WEB_METHODOLOGY_DIR / "engineering.generated.ts": render_level_ts(pkg, "engineering"),
        WEB_METHODOLOGY_DIR / "managementFeeGuidance.generated.ts": render_guidance_ts(guidance),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when any generated file is stale")
    args = parser.parse_args(argv)
    try:
        files = outputs()
    except Exception as exc:  # the loader's MethodologyError lists every problem
        print(f"gen_methodology: {exc}", file=sys.stderr)
        return 2
    stale: list[Path] = []
    for path, content in files.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    if args.check:
        if stale:
            print("gen_methodology: generated files are stale — run scripts/gen_methodology.py:", file=sys.stderr)
            for p in stale:
                print(f"  - {p.relative_to(REPO_ROOT)}", file=sys.stderr)
            return 1
        print("gen_methodology: generated files are up to date")
        return 0
    for p in files:
        print(f"{'wrote' if p in stale else 'unchanged'} {p.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
